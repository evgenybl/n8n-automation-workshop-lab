'use strict';
// Writes instructor/repairs-for-printing.md from participant/repairs.md: the same page for paper, which cannot fold.
// Each repair's folded cause and fix is left out (the instructor keeps them: instructor/answer-key.md), and each folded
// hint is written out as plain text, so that it is on the paper whatever the browser does with folded parts.
//
//   node tools/print-repairs.js           writes the file
//   node tools/print-repairs.js --check   fails if the file differs from what this script writes

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SOURCE = 'participant/repairs.md';
const TARGET = 'instructor/repairs-for-printing.md';

const NOTE = [
  '> **For printing.** This is `' + SOURCE + '` for paper, written by `tools/print-repairs.js`: each repair\'s cause and',
  '> fix is left out, because a printout cannot fold it away, and each hint is written out. The causes are in',
  '> `instructor/answer-key.md`. Do not edit this file; edit the participant page and run the script.',
].join('\n');

function forPrinting(text) {
  const lines = text.split('\n');
  assert(lines[0] === '# The four repairs', 'the page starts with its title');
  let out = text.replace(/^# The four repairs\n/, '# The four repairs, for printing\n\n' + NOTE + '\n');
  // Leave out each cause and fix, with the blank line after it.
  const causes = out.match(/<details><summary>The cause, and the fix<\/summary>\n[\s\S]*?\n<\/details>\n\n/g) || [];
  assert(causes.length === 4, 'four causes, one for each repair; found ' + causes.length);
  for (const c of causes) out = out.replace(c, '');
  // The participant page's note about printing is for the screen only.
  out = out.replace(/\*\*Printing this page\?\*\*[^]*?\n\n/, '');
  // Write each hint out: its folded block becomes a bold label and the same text.
  out = out.replace(/<details><summary>(Hint \d)<\/summary>\n\n([\s\S]*?)\n\n<\/details>\n/g, '**$1.** $2\n');
  assert(!/<details>|<\/details>/.test(out), 'nothing is left folded');
  return out;
}

function assert(ok, message) {
  if (!ok) throw new Error(message);
}

function main(argv) {
  const want = forPrinting(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8'));
  const file = path.join(ROOT, TARGET);
  if (argv.includes('--check')) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have !== want) {
      console.log(TARGET + ' differs from what tools/print-repairs.js writes from ' + SOURCE + '.');
      return 1;
    }
    console.log(TARGET + ' is what tools/print-repairs.js writes from ' + SOURCE + '.');
    return 0;
  }
  fs.writeFileSync(file, want);
  console.log('Wrote ' + TARGET + '.');
  return 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { forPrinting, SOURCE, TARGET };
